/**
 * Public pages served as static files.
 *
 * On the Workers Free plan a request may use 10 ms of CPU, and rendering any
 * page here takes more (docs/SEARCH-AND-AI-VISIBILITY.md), so crawlers and
 * visitors got intermittent 503s. `npm run cf:deploy` therefore deploys once,
 * fetches every public page from the new deployment as an anonymous visitor
 * (scripts/snapshot-pages.ts), writes each into the Worker's static assets and
 * deploys again. Cloudflare serves a request that matches an asset before it
 * runs the Worker, so those pages cost no Worker CPU at all.
 *
 * A page is only fit for this if nothing in it depends on who is asking. The
 * per-visitor parts that remain (the header's sign-in state, the home page's
 * "continue" line, the exam-page view count, and the language redirect that
 * src/proxy.ts makes on a bare path) work in the browser instead when the
 * request carries SNAPSHOT_HEADER.
 */
import { DEFAULT_LOCALE, LOCALES, localizePath, splitLocale, type Locale } from '@/i18n/locales';

/** Sent by the deploy's snapshot; pages that see it defer per-visitor parts to the browser. */
export const SNAPSHOT_HEADER = 'x-examer-snapshot';

export function isSnapshotRequest(headers: { get(name: string): string | null }): boolean {
  return headers.get(SNAPSHOT_HEADER) === '1';
}

/**
 * Sitemap pages (by their English path) that stay dynamic in every language:
 * the plans page shows a signed-in learner their own plan.
 */
export const DYNAMIC_PUBLIC_PATHS: readonly string[] = ['/pricing'];

/** Files crawlers fetch beside the pages, generated by the app rather than kept in public/. */
export const STATIC_EXTRA_PATHS: readonly string[] = [
  '/robots.txt',
  '/sitemap.xml',
  '/llms.txt',
  '/favicon.ico',
  '/icon.svg',
  '/apple-icon.png',
];

/**
 * The paths to save as files, given the URLs in the live sitemap. The sitemap
 * lists each page once, in English; every language has its own URL
 * (src/i18n/routing.ts), so each page is saved in all of them.
 */
export function staticPagePaths(sitemapUrls: readonly string[]): string[] {
  const pages = sitemapUrls
    .map((url) => splitLocale(new URL(url).pathname).path)
    .filter((path) => !DYNAMIC_PUBLIC_PATHS.includes(path))
    .flatMap((path) => LOCALES.map((locale) => localizePath(path, locale)));
  return [...new Set([...pages, ...STATIC_EXTRA_PATHS])];
}

/**
 * What src/proxy.ts (next-intl) does for a page load, for a page saved as a
 * file, which the proxy never sees. On a bare English path it takes the
 * language from the locale cookie, else from the browser's languages, and
 * moves to that language's address if it is not English; on any page it then
 * brings the cookie into line with the page, as the proxy does. Crawlers ask
 * for English, so they stay. Inline and first in <body>, so a visitor who is
 * moved never sees the English page drawn.
 */
export function localeScript(pageLocale: Locale, cookieName: string): string {
  const args = [pageLocale, LOCALES, DEFAULT_LOCALE, cookieName].map((value) => JSON.stringify(value)).join(',');
  return `(function(P,L,D,N){try{var m=document.cookie.match(new RegExp("(?:^|; )"+N+"=([^;]*)")),c=m?decodeURIComponent(m[1]):null;function a(){var n=navigator.languages||[navigator.language||""];for(var i=0;i<n.length;i++){var x=String(n[i]).toLowerCase();for(var j=0;j<L.length;j++)if(x===L[j]||x.split("-")[0]===L[j])return L[j]}return D}if(P===D){var w=c&&L.indexOf(c)>=0?c:a();if(w!==D){location.replace("/"+w+(location.pathname==="/"?"":location.pathname)+location.search+location.hash);return}}if(c?c!==P:a()!==P)document.cookie=N+"="+P+"; path=/; max-age=31536000; samesite=lax"}catch(e){}})(${args});`;
}

/**
 * Where a path's file goes in the assets directory. Cloudflare's default
 * html_handling ("auto-trailing-slash") serves /exams/gmat from
 * exams/gmat.html without a redirect, and / from index.html.
 */
export function assetFileFor(pathname: string): string {
  if (!pathname.startsWith('/') || pathname.includes('..') || pathname.includes('?')) {
    throw new Error(`Not a plain path: ${pathname}`);
  }
  if (pathname === '/') return 'index.html';
  const relative = pathname.replace(/^\/+/, '').replace(/\/+$/, '');
  return /\.[a-z0-9]+$/i.test(relative) ? relative : `${relative}.html`;
}
